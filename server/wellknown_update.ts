/**
 * Regenerates server/wellknown.ts from the files in .well-known/.
 *
 *   deno task wellknown
 *
 * Why the files are copied into a module at all: serveDir treats every path
 * segment that starts with a dot as a dotfile and answers 404 for it, so
 * /.well-known/ has never been reachable through the static fallback (it only
 * looked fine on GitHub Pages, which special-cases it). Android checks
 * /.well-known/assetlinks.json before it will open logosell.app links in the
 * app, so the server answers these paths itself, from this table. A module is
 * also the one thing a deploy is certain to carry; whether `deno deploy`
 * uploads a dot-directory is not something this repository can promise.
 *
 * Run it after editing anything in .well-known/. wellknown_test.ts compares the
 * table with the files byte for byte and names the file that drifted.
 */
const TYPES: Record<string, string> = {
  json: 'application/json; charset=utf-8',
  txt: 'text/plain; charset=utf-8',
};

/** A TypeScript single-quoted string literal, byte-exact. */
function quote(s: string): string {
  let out = '';
  for (const ch of s) {
    const c = ch.codePointAt(0)!;
    if (ch === '\\') out += '\\\\';
    else if (ch === "'") out += "\\'";
    else if (ch === '\n') out += '\\n';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\t') out += '\\t';
    else if (c < 0x20 || c === 0x7f) throw new Error(`control character U+${c.toString(16)}`);
    else out += ch;
  }
  return `'${out}'`;
}

const dir = new URL('../.well-known/', import.meta.url);
const names: string[] = [];
for await (const e of Deno.readDir(dir)) {
  if (!e.isFile) throw new Error(`${e.name}: only plain files are served from .well-known/`);
  names.push(e.name);
}
names.sort();

const entries: string[] = [];
for (const name of names) {
  const type = TYPES[name.split('.').pop() ?? ''];
  if (!type) throw new Error(`${name}: no content type chosen for it; add one to TYPES`);
  const body = await Deno.readTextFile(new URL(name, dir));
  entries.push(
    `  '/.well-known/${name}': {\n    type: ${quote(type)},\n    body: ${quote(body)},\n  },`,
  );
}

const out = `// deno-fmt-ignore-file
// GENERATED by server/wellknown_update.ts from .well-known/ (deno task wellknown).
// Do not edit by hand: wellknown_test.ts compares this table with the files.
export const WELL_KNOWN: Record<string, { type: string; body: string }> = {
${entries.join('\n')}
};
`;
await Deno.writeTextFile(new URL('./wellknown.ts', import.meta.url), out);
console.log(`wrote server/wellknown.ts with ${names.length} files: ${names.join(', ')}`);
